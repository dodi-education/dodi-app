-- Platform database baseline (plain PostgreSQL 17).
--
-- Squashed from the former Supabase migration chain (baseline 20260613120000
-- through 20260803120000) with the provider-specific parts removed:
--   * no Supabase roles/grants/extensions; only core gen_random_uuid() is used
--   * RLS policies read the request identity from app.current_account_id()
--     (a per-connection setting stamped by platform/src/lib/db.ts) instead of
--     auth.uid()
--   * accounts are provisioned from the Better Auth user table (auth_users)
--     by handle_new_user(), replacing the trigger on auth.users
--   * system rows (default persona, system games, plans, config) are part of
--     the baseline so a migrated database is complete without a seed step
--
-- Roles: dodi_app (RLS enforced) and dodi_service (BYPASSRLS) are created
-- NOLOGIN here if missing so this file also works in tests; deployments create
-- them with passwords first (ops/hosting/postgres/init).
--
-- Applied by db/migrate.ts (Kysely Migrator). Reverse: drop the database.

SET check_function_bodies = false;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dodi_app') THEN
    CREATE ROLE dodi_app NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dodi_service') THEN
    CREATE ROLE dodi_service NOLOGIN BYPASSRLS;
  END IF;
END
$$;

