### set_drawing_color
Change the active brush color.
- `payload.color` (string, required): A hex color from the palette: `#111111`, `#ffffff`, `#757575`, `#894b17`, `#e53935`, `#fb8c00`, `#fdd835`, `#43a047`, `#1e88e5`, `#8e24aa`, `#ff5ca8`
