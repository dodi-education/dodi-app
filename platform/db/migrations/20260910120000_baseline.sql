-- Name: discover_game_stats(uuid[]); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.discover_game_stats(p_game_ids uuid[]) RETURNS TABLE(game_id uuid, plays bigint, copies bigint)
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'public', 'pg_temp'
    AS $$
    select
      g.id as game_id,
      (select count(*) from public.game_plays p where p.game_id = g.id) as plays,
      (select count(*) from public.games c
         where c.source_game_id = g.id
           and c.publication_requested_at is null) as copies
    from unnest(p_game_ids) as g(id);
  $$;


--
-- Name: handle_new_user(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.handle_new_user() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    AS $$
declare
  v_code text;
begin
  insert into public.accounts (id, email)
  values (new.id, new.email)
  on conflict (id) do nothing;

  -- Record an invite-code redemption if one was supplied at signup (the
  -- registration gate in lib/auth.ts already validated it). Recording must
  -- never block signup.
  v_code := nullif(btrim(new.invite_code), '');
  if v_code is not null then
    perform public.redeem_invite_code(v_code, new.id);
  end if;

  return new;
end;
$$;


